import { supabase } from "./supabase";

/**
 * Записать контакт и согласие после входа.
 *
 * Почта и телефон берутся базой из подписанного токена, а не отсюда: со слов
 * браузера в базу контактов можно было бы записать что угодно. Отсюда идёт
 * только ответ на вопрос о рассылке.
 *
 * Ошибку глушим намеренно: не записался профиль — человек всё равно вошёл,
 * и мешать ему из-за этого нельзя.
 */
export async function rememberContact(consent: boolean | null): Promise<void> {
  await supabase.rpc("touch_profile", { consent });
}
